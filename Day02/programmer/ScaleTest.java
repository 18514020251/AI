public class ScaleTest {
    public static void main(String[] args) {
        // 1010111
        System.out.println("十进制" + 1010111);
        System.out.println("二进制" + 0B1010111); // 0B
        System.out.println("八进制" + 01010111); // 0开头
        System.out.println("十六进制" + 0x1010111); // 0x
    }
}
